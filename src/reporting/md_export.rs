fn card_html(tone: &str, color: &str, ico: &str, label: &str, value: &str, sub: &str) -> String {
    let value = html_escape(value);
    let label = html_escape(label);
    let sub_html = if sub.is_empty() {
        String::new()
    } else {
        format!(" <span class=\"sub\">{}</span>", html_escape(sub))
    };
    format!(
        "<div class=\"summary-card {0}\"><div class=\"ico\">{1}</div><div class=\"body\"><div class=\"num {2}\">{3}</div><div class=\"label\">{4}{5}</div></div></div>",
        tone, ico, color, value, label, sub_html
    )
}

/// Split an "Overall Health" value like `🟡 Good (Score: 82.4)` into
/// `(main_text, score)`.
fn split_health(value: &str) -> (String, String) {
    let mut main = value.trim().to_string();
    let mut score = String::new();
    let digits = |rest: &str| {
        rest.trim_start()
            .chars()
            .take_while(|c| c.is_ascii_digit() || *c == '.')
            .collect::<String>()
    };
    if let Some(p) = main.find("(Score:") {
        score = digits(&main[p + "(Score:".len()..]);
        main = main[..p].trim().to_string();
    } else if let Some(p) = main.find("（得分：") {
        score = digits(&main[p + "（得分：".len()..]);
        main = main[..p].trim().to_string();
    }
    (main, score)
}

fn health_tone(value: &str) -> (&'static str, &'static str) {
    if value.contains('🟢') {
        ("s-ok", "green")
    } else if value.contains('🟡') || value.contains('🟠') {
        ("s-warn", "orange")
    } else if value.contains('🔴') || value.contains('🚨') {
        ("s-crit", "red")
    } else {
        ("s-info", "blue")
    }
}

/// Summary stat cards from the Cluster Overview table (mirrors the reference style).
fn build_summary_cards(rows: &[(String, String)], lang: Lang) -> String {
    let mut cards: Vec<String> = Vec::new();
    if let Some(v) = overview_value(rows, "集群版本", "Cluster Version") {
        cards.push(card_html(
            "s-purple",
            "purple",
            icon("version"),
            short_label(lang, "version"),
            v,
            "",
        ));
    }
    if let Some(v) = overview_value(rows, "节点数", "Node Count") {
        let sub = match overview_value(rows, "就绪节点数", "Ready Nodes") {
            Some(ready) => match lang {
                Lang::Zh => format!("就绪 {} / {}", ready, v),
                Lang::En => format!("ready {} / {}", ready, v),
            },
            None => String::new(),
        };
        cards.push(card_html(
            "s-info",
            "blue",
            icon("nodes"),
            short_label(lang, "nodes"),
            v,
            &sub,
        ));
    }
    if let Some(v) = overview_value(rows, "Pod 数", "Pod Count") {
        cards.push(card_html(
            "s-orange",
            "orange",
            icon("pods"),
            short_label(lang, "pods"),
            v,
            "",
        ));
    }
    if let Some(v) = overview_value(rows, "命名空间数", "Namespace Count") {
        cards.push(card_html(
            "s-ok",
            "green",
            icon("ns"),
            short_label(lang, "ns"),
            v,
            "",
        ));
    }
    if let Some(v) = overview_value(rows, "集群年龄（天）", "Cluster Age (days)") {
        cards.push(card_html(
            "s-info",
            "blue",
            icon("age"),
            short_label(lang, "age"),
            v,
            "",
        ));
    }
    if let Some(v) = overview_value(rows, "总体健康状态", "Overall Health") {
        let (tone, color) = health_tone(v);
        let (main, score) = split_health(v);
        let sub = if score.is_empty() {
            String::new()
        } else {
            match lang {
                Lang::Zh => format!("得分 {}", score),
                Lang::En => format!("score {}", score),
            }
        };
        cards.push(card_html(
            tone,
            color,
            icon("health"),
            short_label(lang, "health"),
            &main,
            &sub,
        ));
    }
    if cards.is_empty() {
        return String::new();
    }
    format!("<div class=\"summary\">{}</div>", cards.join(""))
}

/// Blue gradient header banner with report meta.
fn build_header(p: &ParsedReport, lang: Lang) -> String {
    let (tag, id_k, cluster_k, gen_k, ver_k) = match lang {
        Lang::Zh => ("集群巡检", "报告 ID", "集群", "生成时间", "工具版本"),
        Lang::En => (
            "Cluster Check",
            "Report ID",
            "Cluster",
            "Generated At",
            "Version",
        ),
    };
    let title = if p.title.is_empty() {
        lang.html_title()
    } else {
        p.title.as_str()
    };
    let version = env!("CARGO_PKG_VERSION");
    format!(
        "<div class=\"header\"><div class=\"header-top\"><h1><span class=\"tag\">{0}</span>{1}</h1><span class=\"header-action\">HTML</span></div><div class=\"header-meta\"><div class=\"field\"><span class=\"k\">{2}:</span><span class=\"v\">{3}</span></div><div class=\"field\"><span class=\"k\">{4}:</span><span class=\"v\">{5}</span></div><div class=\"field\"><span class=\"k\">{6}:</span><span class=\"v\">{7}</span></div><div class=\"field\"><span class=\"k\">{8}:</span><span class=\"v\">v{9}</span></div></div></div>",
        tag,
        html_escape(title),
        id_k,
        html_escape(&p.report_id),
        cluster_k,
        html_escape(&p.cluster),
        gen_k,
        html_escape(&p.generated_at),
        ver_k,
        version
    )
}

/// Convert Markdown string to a full themed HTML document in the requested language.
pub fn md_to_html(md: &str, lang: Lang) -> Result<String> {
    let parsed = parse_report(md);

    let mut opts = ComrakOptions::default();
    opts.extension.table = true;
    let body = markdown_to_html(&parsed.body_md, &opts);
    let sections = wrap_sections(&body);

    let logo_src = embedded_logo_data_uri();
    let toc = build_toc(&parsed.headings, &logo_src);
    let header = build_header(&parsed, lang);
    let cards = build_summary_cards(&parsed.overview, lang);
    let footer = match lang {
        Lang::Zh => "报告由 kcc 生成",
        Lang::En => "Report generated by kcc",
    };

    let mut html = String::with_capacity(16_384);
    html.push_str("<!DOCTYPE html>\n<html lang=\"");
    html.push_str(lang.html_lang());
    html.push_str("\">\n<head>\n<meta charset=\"UTF-8\"/>\n<meta name=\"viewport\" content=\"width=device-width, initial-scale=1.0\"/>\n<title>");
    html.push_str(lang.html_title());
    html.push_str("</title>\n<style>\n");
    html.push_str(THEME_CSS);
    html.push_str("\n</style>\n</head>\n<body>\n");
    html.push_str(&toc);
    html.push_str("<div class=\"container\">\n");
    html.push_str(&header);
    if !cards.is_empty() {
        html.push_str(&cards);
    }
    html.push_str(&sections);
    html.push_str(&format!("<div class=\"footer\">{}</div>\n</div>\n", footer));
    html.push_str(THEME_JS);
    html.push_str("</body>\n</html>");
    Ok(html)
}

