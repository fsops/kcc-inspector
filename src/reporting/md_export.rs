fn escape_csv(s: &str) -> String {
    if s.contains(',') || s.contains('"') || s.contains('\n') {
        format!("\"{}\"", s.replace('"', "\"\""))
    } else {
        s.to_string()
    }
}

/// Extract rule_id from a markdown link like [STO-409](url) or plain text.
fn extract_rule_id(cell: &str) -> String {
    let cell = cell.trim();
    if let Some(start) = cell.find('[') {
        if let Some(end) = cell[start..].find(']') {
            return cell[start + 1..start + end].to_string();
        }
    }
    cell.to_string()
}

/// Parse MD and convert to CSV: cluster_overview row + issue rows from per-resource tables.
pub fn md_to_csv(md: &str) -> Result<String> {
    let mut out = String::new();
    let lines: Vec<&str> = md.lines().collect();

    let mut cluster_name = String::new();
    let mut report_id = String::new();
    let mut overview: std::collections::HashMap<String, String> = std::collections::HashMap::new();
    let mut seen_cluster_overview = false;
    let mut in_overview_table = false;
    let mut overview_done = false;
    let mut current_section = String::new();
    let mut issue_rows: Vec<(String, String, String, String, String)> = Vec::new(); // section, resource, level, rule_id, short_title

    let mut i = 0;
    while i < lines.len() {
        let line = lines[i];
        if line.starts_with("**Cluster**:") || line.starts_with("**集群**：") {
            let prefix = if line.starts_with("**Cluster**:") {
                "**Cluster**:"
            } else {
                "**集群**："
            };
            cluster_name = line
                .trim_start_matches(prefix)
                .trim()
                .trim_matches(' ')
                .to_string();
        } else if line.starts_with("**Report ID**:") || line.starts_with("**报告 ID**：") {
            let prefix = if line.starts_with("**Report ID**:") {
                "**Report ID**:"
            } else {
                "**报告 ID**："
            };
            report_id = line
                .trim_start_matches(prefix)
                .trim()
                .trim_matches('`')
                .trim()
                .to_string();
        } else if (line.contains("Cluster Overview") || line.contains("集群概览"))
            && (line.starts_with("##") || line.contains("🖥️"))
        {
            seen_cluster_overview = true;
        } else if !overview_done
            && (seen_cluster_overview || in_overview_table)
            && line.starts_with('|')
        {
            let cells: Vec<&str> = line
                .split('|')
                .map(|c| c.trim())
                .filter(|c| !c.is_empty())
                .collect();
            let is_overview_header = cells.len() >= 2
                && ((cells[0] == "Metric" && cells[1] == "Value")
                    || (cells[0] == "指标" && cells[1] == "值"));
            if is_overview_header {
                in_overview_table = true;
                seen_cluster_overview = false;
            } else if in_overview_table
                && cells.len() >= 2
                && !cells[0].chars().all(|c| c == '-' || c == ' ')
            {
                // Normalize localized metric labels to canonical English keys.
                let canonical = match cells[0] {
                    "Cluster Version" | "集群版本" => "Cluster Version",
                    "Node Count" | "节点数" => "Node Count",
                    "Ready Nodes" | "就绪节点数" => "Ready Nodes",
                    "Pod Count" | "Pod 数" => "Pod Count",
                    "Namespace Count" | "命名空间数" => "Namespace Count",
                    "Cluster Age (days)" | "集群年龄（天）" => "Cluster Age (days)",
                    other => other,
                };
                overview.insert(canonical.to_string(), cells[1].to_string());
            }
        } else if in_overview_table && (!line.starts_with('|') || line.trim().is_empty()) {
            in_overview_table = false;
            overview_done = true;
        }
        if line.starts_with("## ")
            && !line.contains("Cluster Overview")
            && !line.contains("集群概览")
        {
            seen_cluster_overview = false;
        }

        if line.starts_with("### ") && !line.starts_with("#### ") {
            current_section = line.trim_start_matches("### ").trim().to_string();
        }

        let is_issue_table_header = (line.contains("Resource")
            && line.contains("Level")
            && line.contains("Issue Code")
            && line.contains("Short Title"))
            || (line.contains("资源")
                && line.contains("级别")
                && line.contains("问题代码")
                && line.contains("简要描述"));
        if line.starts_with('|') && is_issue_table_header {
            // Note: also matches the Chinese localized header (资源 | 级别 | 问题代码 | 简要描述).
            i += 1;
            if i < lines.len() && lines[i].contains("---") {
                i += 1;
            }
            while i < lines.len() && lines[i].starts_with('|') {
                let row = lines[i];
                let cells: Vec<&str> = row
                    .split('|')
                    .map(|c| c.trim())
                    .filter(|c| !c.is_empty())
                    .collect();
                if cells.len() >= 4 && !cells[0].chars().all(|c| c == '-') {
                    let resource = cells[0].trim_matches('`').to_string();
                    let level = cells[1].to_string();
                    let rule_id = extract_rule_id(cells.get(2).unwrap_or(&""));
                    let short_title = cells.get(3).unwrap_or(&"").to_string();
                    issue_rows.push((
                        current_section.clone(),
                        resource,
                        level,
                        rule_id,
                        short_title,
                    ));
                }
                i += 1;
            }
            continue;
        }
        i += 1;
    }

    out.push_str("section,cluster_name,report_id,cluster_version,node_count,ready_node_count,pod_count,namespace_count,cluster_age_days\n");
    let cv = overview.get("Cluster Version").cloned().unwrap_or_default();
    let nn = overview.get("Node Count").cloned().unwrap_or_default();
    let rn = overview.get("Ready Nodes").cloned().unwrap_or_default();
    let pc = overview.get("Pod Count").cloned().unwrap_or_default();
    let ns = overview.get("Namespace Count").cloned().unwrap_or_default();
    let age = overview
        .get("Cluster Age (days)")
        .cloned()
        .unwrap_or_default();
    out.push_str(&format!(
        "cluster_overview,{},{},{},{},{},{},{},{}\n",
        escape_csv(&cluster_name),
        escape_csv(&report_id),
        escape_csv(&cv),
        escape_csv(&nn),
        escape_csv(&rn),
        escape_csv(&pc),
        escape_csv(&ns),
        escape_csv(&age)
    ));

    out.push_str(
        "section,inspection_type,severity,category,description,resource,recommendation,rule_id\n",
    );
    for (section, resource, level, rule_id, short_title) in issue_rows {
        out.push_str(&format!(
            "issue,{0},{1},{2},{3},{4},{5},{6},{7}\n",
            escape_csv(&section),
            escape_csv(&section),
            escape_csv(&level),
            escape_csv(&section),
            escape_csv(&short_title),
            escape_csv(&resource),
            escape_csv(""),
            escape_csv(&rule_id),
        ));
    }

    Ok(out)
}

