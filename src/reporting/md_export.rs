//! Export report from Markdown: MD -> HTML (comrak + themed template), MD -> CSV (parse tables).
//!
//! The HTML export wraps the comrak-rendered body in a self-contained "Token Insight"
//! style document: dark sidebar TOC with scroll-spy, a blue gradient header banner with
//! report meta, summary stat cards derived from the Cluster Overview table, numbered
//! section cards, colored status badges, and percentage progress bars.

use anyhow::Result;
use base64::Engine;
use comrak::{markdown_to_html, ComrakOptions};

use crate::utils::lang::Lang;

/// Logo image embedded at compile time; encoded as data URI so HTML report is self-contained.
fn embedded_logo_data_uri() -> String {
    let bytes = include_bytes!("../../web/logo.png");
    format!(
        "data:image/png;base64,{}",
        base64::engine::general_purpose::STANDARD.encode(bytes)
    )
}

/// Escape text for safe embedding into HTML attributes / text nodes.
fn html_escape(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            _ => out.push(c),
        }
    }
    out
}

/// Markdown structure extracted before rendering: title, header fields, overview
/// metrics (for the summary cards), headings (for the TOC) and the body to render.
struct ParsedReport {
    title: String,
    report_id: String,
    cluster: String,
    generated_at: String,
    overview: Vec<(String, String)>,
    headings: Vec<(u8, String)>,
    body_md: String,
}

/// Strip a `**Key**: value` / `**键**：值` field, trimming markdown/backticks.
fn field_value(line: &str, en: &str, zh: &str) -> Option<String> {
    let value = line.strip_prefix(en).or_else(|| line.strip_prefix(zh))?;
    Some(value.trim().trim_matches('`').trim().to_string())
}

fn is_metric_value_header(cells: &[&str]) -> bool {
    cells.len() >= 2
        && ((cells[0] == "Metric" && cells[1] == "Value")
            || (cells[0] == "指标" && cells[1] == "值"))
}

/// Parse the markdown report into its structural parts. The body keeps every table
/// (including the Cluster Overview one, which is also harvested for summary cards);
/// only the h1 title, the header fields and the footer lines are moved out.
fn parse_report(md: &str) -> ParsedReport {
    let mut title = String::new();
    let mut report_id = String::new();
    let mut cluster = String::new();
    let mut generated_at = String::new();
    let mut overview: Vec<(String, String)> = Vec::new();
    let mut headings: Vec<(u8, String)> = Vec::new();
    let mut body: Vec<&str> = Vec::new();
    let mut in_overview = false;
    let mut seen_subsection = false; // once an "###" appears, the Metric|Value table is no longer the cluster overview

    for line in md.lines() {
        let t = line.trim();
        // h1 title -> banner (skip in body)
        if title.is_empty() && t.starts_with("# ") && !t.starts_with("## ") {
            title = t[2..].trim().to_string();
            continue;
        }
        // Header fields -> banner meta
        if let Some(v) = field_value(t, "**Report ID**:", "**报告 ID**：") {
            report_id = v;
            continue;
        }
        if let Some(v) = field_value(t, "**Cluster**:", "**集群**：") {
            cluster = v;
            continue;
        }
        if let Some(v) = field_value(t, "**Generated At**:", "**生成时间**：") {
            generated_at = v;
            continue;
        }
        // Footer lines and horizontal rules are rendered by the themed template.
        if t.starts_with("*Report generated by") || t.starts_with("*报告由") || t == "---" {
            continue;
        }
        // Headings -> TOC
        if let Some(rest) = t.strip_prefix("### ") {
            seen_subsection = true;
            in_overview = false;
            headings.push((3, rest.trim().to_string()));
            body.push(line);
            continue;
        }
        if let Some(rest) = t.strip_prefix("## ") {
            in_overview = false;
            headings.push((2, rest.trim().to_string()));
            body.push(line);
            continue;
        }
        // Cluster Overview Metric|Value table (only the one before the first subsection)
        if !seen_subsection && t.starts_with('|') {
            let cells: Vec<&str> = t
                .split('|')
                .map(|c| c.trim())
                .filter(|c| !c.is_empty())
                .collect();
            if !in_overview && is_metric_value_header(&cells) {
                in_overview = true;
                body.push(line);
                continue;
            }
            if in_overview {
                if cells.len() >= 2 && !cells.iter().all(|c| c.chars().all(|ch| ch == '-')) {
                    overview.push((cells[0].to_string(), cells[1].to_string()));
                }
                body.push(line);
                continue;
            }
        }
        if !t.starts_with('|') {
            in_overview = false;
        }
        body.push(line);
    }

    ParsedReport {
        title,
        report_id,
        cluster,
        generated_at,
        overview,
        headings,
        body_md: body.join("\n") + "\n",
    }
}

/// Wrap each `<table>…</table>` in a horizontal-scroll container.
fn wrap_tables(content: &str) -> String {
    let mut out = String::with_capacity(content.len());
    let mut rest = content;
    loop {
        match rest.find("<table") {
            None => {
                out.push_str(rest);
                break;
            }
            Some(p) => {
                out.push_str(&rest[..p]);
                let after = &rest[p..];
                match after.find("</table>") {
                    Some(e) => {
                        let end = e + "</table>".len();
                        out.push_str("<div class=\"table-scroll\">");
                        out.push_str(&after[..end]);
                        out.push_str("</div>");
                        rest = &after[end..];
                    }
                    None => {
                        out.push_str(after);
                        break;
                    }
                }
            }
        }
    }
    out
}

/// Number `<h3>` headings (inject `id="sub-N"`) within a section's content.
fn inject_sub_ids(content: &str, sub: &mut usize) -> String {
    let mut out = String::with_capacity(content.len());
    let mut rest = content;
    loop {
        match rest.find("<h3>") {
            None => {
                out.push_str(rest);
                break;
            }
            Some(p) => {
                out.push_str(&rest[..p]);
                *sub += 1;
                out.push_str(&format!("<h3 id=\"sub-{}\">", *sub));
                rest = &rest[p + "<h3>".len()..];
            }
        }
    }
    out
}

/// Section content: wrap tables, assign h3 ids.
fn wrap_content(content: &str, sub: &mut usize) -> String {
    inject_sub_ids(&wrap_tables(content), sub)
}

/// Split the comrak-rendered body into numbered `<section>` cards (`id="sec-N"`),
/// one per `<h2>` block, and assign ids to `<h3>` sub-headings.
fn wrap_sections(body: &str) -> String {
    let mut out = String::with_capacity(body.len() + 512);
    let mut rest = body;
    let mut sub = 0usize;

    match rest.find("<h2") {
        None => {
            // No h2 at all: wrap everything in a single section.
            return format!(
                "<section class=\"section\">{}</section>",
                wrap_content(rest, &mut sub)
            );
        }
        Some(pos) => {
            let lead = &rest[..pos];
            if !lead.trim().is_empty() {
                out.push_str("<section class=\"section\">");
                out.push_str(&wrap_content(lead, &mut sub));
                out.push_str("</section>");
            }
            rest = &rest[pos..];
        }
    }

    let mut sec = 0usize;
    while !rest.is_empty() {
        // `rest` starts with "<h2"; locate the whole tag.
        let close_pos = rest.find("</h2>").expect("h2 tag must be closed");
        let h2_full_end = close_pos + "</h2>".len();
        let h2_tag = &rest[..h2_full_end];
        let open_end = h2_tag.find('>').expect("h2 open tag");
        sec += 1;
        out.push_str(&format!("<section class=\"section\" id=\"sec-{}\">", sec));
        out.push_str(&format!("<h2><span class=\"num\">{}.</span>", sec));
        let inner = &h2_tag[open_end + 1..]; // heading text + closing </h2>
        out.push_str(inner);

        let after_h2 = &rest[h2_full_end..];
        match after_h2.find("<h2") {
            Some(p) => {
                out.push_str(&wrap_content(&after_h2[..p], &mut sub));
                rest = &after_h2[p..];
            }
            None => {
                out.push_str(&wrap_content(after_h2, &mut sub));
                rest = "";
            }
        }
        out.push_str("</section>");
    }
    out
}

/// Build the dark sidebar TOC from the heading list. All `<h3>` sub-links are
/// shown so every section (including "Detailed Results") supports sub-navigation.
fn build_toc(headings: &[(u8, String)], logo_src: &str) -> String {
    let version = env!("CARGO_PKG_VERSION");
    let mut out = String::new();
    out.push_str("<nav class=\"toc\">");
    out.push_str(&format!(
        "<div class=\"toc-brand\"><img class=\"logo-img\" src=\"{0}\" alt=\"logo\"/><div class=\"meta\"><div class=\"name\">kcc</div><div class=\"ver\">v{1}</div></div></div>",
        logo_src, version
    ));
    let mut h2_idx = 0usize;
    let mut h3_idx = 0usize;
    let mut i = 0usize;
    while i < headings.len() {
        if headings[i].0 == 2 {
            h2_idx += 1;
            out.push_str(&format!(
                "<a href=\"#sec-{}\">{}</a>",
                h2_idx,
                html_escape(&headings[i].1)
            ));
            let mut j = i + 1;
            let mut subs: Vec<(usize, String)> = Vec::new();
            while j < headings.len() && headings[j].0 == 3 {
                h3_idx += 1;
                subs.push((h3_idx, headings[j].1.clone()));
                j += 1;
            }
            for (sid, text) in subs {
                out.push_str(&format!(
                    "<a class=\"sub\" href=\"#sub-{}\">{}</a>",
                    sid,
                    html_escape(&text)
                ));
            }
            i = j;
        } else {
            h3_idx += 1;
            i += 1;
        }
    }
    out.push_str("</nav>");
    out
}

/// Look up a localized overview row value (both language labels are matched).
fn overview_value<'a>(rows: &'a [(String, String)], zh: &str, en: &str) -> Option<&'a str> {
    rows.iter()
        .find(|(l, _)| l == zh || l == en)
        .map(|(_, v)| v.as_str())
}

